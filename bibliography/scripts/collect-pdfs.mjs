#!/usr/bin/env node
/**
 * collect-pdfs.mjs — build a collection of the works' PDFs, OUTSIDE the repo.
 *
 *   node scripts/collect-pdfs.mjs --dir "$HOME/Documents/Research/Exhaustive Bibliography"
 *   node scripts/collect-pdfs.mjs --dir … --email you@example.edu        # Unpaywall contact
 *   node scripts/collect-pdfs.mjs --dir … --manifest-only                # refresh the manifest only
 *
 * Why outside the repo: the repo is a deploy target, and holding full texts in it would contradict the
 * publication's posture (D9 — quoted extracts only, never a full text). The collection lives in its own
 * folder; what lives in the repo is the *record* of it (this script and the manifest it writes).
 *
 * What it can get by itself: anything with an open-access PDF it can reach over plain HTTP — publisher
 * OA (Springer, MDPI, PLOS, Wiley OA …) and repository copies that serve a real PDF. Unpaywall supplies
 * the candidate URL for a DOI. What it cannot get: paywalled journal articles (NEJM, JAMA, BMJ, most
 * Elsevier/Wiley/T&F) and print-only books, which need a library session — those are written out as a
 * fetch list instead, and the manifest says so per work.
 *
 * Files land as <dir>/pdf/<citekey>.pdf and are validated (must start with %PDF-). Nothing is written
 * inside the repo: the script refuses a --dir that is the repo or lives under it.
 */
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { load, shortLabel, apaEntry } from './build.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const REPO = path.resolve(ROOT, '..')
const UA = 'Mozilla/5.0 (compatible; magnifica-bibliography/1.0; +mailto:bschoedel@miners.utep.edu)'

const arg = (flag, fallback = undefined) => {
  const i = process.argv.indexOf(flag)
  return i === -1 ? fallback : process.argv[i + 1]
}
const has = (flag) => process.argv.includes(flag)

/** Candidate URLs for an entry, most likely first. */
export function candidates(entry, unpaywall) {
  const out = []
  const add = (u, why) => {
    if (u && !out.some((c) => c.url === u)) out.push({ url: u, why })
  }
  if (entry.url && /\.pdf($|\?)/i.test(entry.url)) add(entry.url, 'the entry’s own URL')
  const oa = unpaywall?.best_oa_location
  if (oa?.url_for_pdf) add(oa.url_for_pdf, `Unpaywall (${oa.host_type ?? 'host'}, ${oa.version ?? 'version unknown'})`)
  if (entry.doi?.startsWith('10.1007/')) add(`https://link.springer.com/content/pdf/${entry.doi}.pdf`, 'Springer open access')
  if (entry.doi?.startsWith('10.1371/')) add(`https://journals.plos.org/plosone/article/file?id=${entry.doi}&type=printable`, 'PLOS')
  if (entry.doi && /ncbi\.nlm\.nih\.gov\/pmc\/articles\/(PMC\d+)/.test(entry.url ?? '')) {
    const pmcid = entry.url.match(/(PMC\d+)/)[1]
    add(`https://europepmc.org/articles/${pmcid}?pdf=render`, 'Europe PMC')
    add(`https://pmc.ncbi.nlm.nih.gov/articles/${pmcid}/pdf/`, 'PMC')
  }
  return out
}

async function fetchPdf(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/pdf,*/*' }, redirect: 'follow' })
  const buf = Buffer.from(await res.arrayBuffer())
  const isPdf = buf.subarray(0, 5).toString('latin1') === '%PDF-'
  return { status: res.status, isPdf, buf, type: res.headers.get('content-type') ?? '' }
}

async function unpaywallFor(doi, email) {
  const res = await fetch(`https://api.unpaywall.org/v2/${encodeURIComponent(doi)}?email=${encodeURIComponent(email)}`, {
    headers: { 'User-Agent': UA },
  })
  if (!res.ok) return null
  return res.json()
}

function sha(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex')
}

function manifest(dir, entries, state) {
  const held = entries.filter((e) => state.files[e.id])
  const missing = entries.filter((e) => !state.files[e.id])
  const out = []
  out.push('# Exhaustive Bibliography — file collection')
  out.push('')
  out.push(
    `${held.length} of ${entries.length} works have a file here. Generated by \`bibliography/scripts/collect-pdfs.mjs\` in the` +
      ' magnifica-humanitas repo; the PDFs themselves stay outside the repo (the publication quotes extracts only — D9).'
  )
  out.push('')
  out.push('## Held')
  out.push('')
  out.push('| Work | File | Source |')
  out.push('| --- | --- | --- |')
  for (const e of held.sort((a, b) => shortLabel(a).localeCompare(shortLabel(b)))) {
    const f = state.files[e.id]
    out.push(`| ${shortLabel(e)} — ${e.title} | \`pdf/${e.id}.pdf\` (${(f.bytes / 1024).toFixed(0)} KB) | ${f.why} |`)
  }
  out.push('')
  out.push('## Still to fetch')
  out.push('')
  out.push('| # | Work | Where | Route |')
  out.push('| --- | --- | --- | --- |')
  const route = (e) => {
    if (e.kind === 'book') return 'print only — not obtainable as a file here'
    if (e.doi) return `library session (DOI ${e.doi})`
    if (e.url) return 'the publisher’s own page'
    return 'no locator recorded — see the entry’s to_verify'
  }
  const seedOf = (e) => entries.find((s) => s.id === (e.seen_in ?? [])[0])
  const inList = (e) => {
    const seed = seedOf(e)
    return seed ? `${shortLabel(seed).replace(/ \(.*\)$/, '')} ${e.ref_no ?? '—'}` : '—'
  }
  for (const e of missing.sort((a, b) => String(inList(a)).localeCompare(String(inList(b))) || shortLabel(a).localeCompare(shortLabel(b)))) {
    const where = e.doi ? `https://doi.org/${e.doi}` : e.url ?? '—'
    out.push(`| ${inList(e)} | ${shortLabel(e)} — ${e.title} | ${where} | ${route(e)} |`)
  }
  out.push('')
  out.push('## Files the collector could not reach')
  out.push('')
  for (const e of missing.filter((e) => state.failed[e.id])) out.push(`- **${e.id}** — ${state.failed[e.id]}`)
  out.push('')
  return out.join('\n')
}

async function main() {
  const dir = arg('--dir', path.join(process.env.HOME, 'Documents/Research/Exhaustive Bibliography'))
  const email = arg('--email', 'bschoedel@miners.utep.edu')
  const resolvedDir = path.resolve(dir)
  if (resolvedDir === REPO || resolvedDir.startsWith(REPO + path.sep))
    throw new Error(`refusing to download into the repo (${resolvedDir}); choose a folder outside ${REPO}`)

  const { entries } = load(ROOT)
  const pdfDir = path.join(resolvedDir, 'pdf')
  fs.mkdirSync(pdfDir, { recursive: true })
  const stateFile = path.join(resolvedDir, 'state.json')
  const state = fs.existsSync(stateFile)
    ? JSON.parse(fs.readFileSync(stateFile, 'utf8'))
    : { files: {}, failed: {}, unpaywall: {} }
  state.files ??= {}
  state.failed ??= {}
  state.unpaywall ??= {}

  // The folder is the truth: whatever PDFs are in it are held, however they arrived (this script, a
  // library session, a browser download, Barry's own filing). state.json only adds provenance.
  for (const f of fs.readdirSync(pdfDir).filter((f) => f.endsWith('.pdf'))) {
    const id = f.slice(0, -4)
    const buf = fs.readFileSync(path.join(pdfDir, f))
    if (!buf.subarray(0, 5).equals(Buffer.from('%PDF-'))) continue
    state.files[id] = { bytes: buf.length, sha256: sha(buf), ...(state.files[id] ?? {}) }
    state.files[id].why ??= 'in the folder (source not recorded)'
    delete state.failed[id]
  }

  if (!has('--manifest-only')) {
    for (const e of entries) {
      const target = path.join(pdfDir, `${e.id}.pdf`)
      if (fs.existsSync(target)) {
        const buf = fs.readFileSync(target)
        state.files[e.id] = state.files[e.id] ?? { bytes: buf.length, sha256: sha(buf), why: 'held before this run' }
        continue
      }
      // entries that are the seed essays themselves are worth having too
      const list = candidates(e, state.unpaywall[e.doi])
      if (e.doi && state.unpaywall[e.doi] === undefined) {
        const uw = await unpaywallFor(e.doi, email)
        state.unpaywall[e.doi] = uw
          ? { is_oa: uw.is_oa, best_oa_location: uw.best_oa_location ? { url_for_pdf: uw.best_oa_location.url_for_pdf, host_type: uw.best_oa_location.host_type, version: uw.best_oa_location.version } : null }
          : null
        list.push(...candidates(e, state.unpaywall[e.doi]))
      }
      if (!list.length) {
        state.failed[e.id] = 'no candidate URL (no DOI, no direct PDF link)'
        continue
      }
      let saved = false
      const why = []
      for (const c of list) {
        try {
          const r = await fetchPdf(c.url)
          if (r.isPdf && r.buf.length > 2048) {
            fs.writeFileSync(target, r.buf)
            state.files[e.id] = { bytes: r.buf.length, sha256: sha(r.buf), why: c.why, url: c.url, fetched: new Date().toISOString().slice(0, 10) }
            delete state.failed[e.id]
            console.log(`saved  ${e.id}  (${(r.buf.length / 1024).toFixed(0)} KB, ${c.why})`)
            saved = true
            break
          }
          why.push(`${c.why}: HTTP ${r.status} ${r.type}`)
        } catch (err) {
          why.push(`${c.why}: ${err.message}`)
        }
      }
      if (!saved) {
        state.failed[e.id] = why.join(' | ') || 'no candidate returned a PDF'
        console.log(`miss   ${e.id}  ${state.failed[e.id]}`)
      }
      await new Promise((r) => setTimeout(r, 400))
    }
  }

  fs.writeFileSync(stateFile, JSON.stringify(state, null, 1))
  fs.writeFileSync(path.join(resolvedDir, 'MANIFEST.md'), manifest(resolvedDir, entries, state))
  const seedOf = (e) => entries.find((s) => s.id === (e.seen_in ?? [])[0])
  const rows = [['in_list', 'ref_no', 'citekey', 'work', 'doi', 'url', 'link', 'route']]
  for (const e of entries) {
    const seed = seedOf(e)
    rows.push([
      seed ? shortLabel(seed).replace(/ \(.*\)$/, '') : '',
      e.ref_no ?? '',
      e.id,
      `${shortLabel(e)} — ${e.title}`,
      e.doi ?? '',
      e.url ?? '',
      e.url ?? (e.doi ? `https://doi.org/${e.doi}` : ''),
      state.files[e.id] ? 'held' : e.kind === 'book' ? 'print only' : 'library session',
    ])
  }
  fs.writeFileSync(path.join(resolvedDir, 'fetch-list.csv'), rows.map((r) => r.map((c) => `"${String(c).replace(/"/g, '""')}"`).join(',')).join('\n') + '\n')
  const held = Object.keys(state.files).length
  console.log(`\n${held} of ${entries.length} works held in ${pdfDir}`)
  console.log(`manifest: ${path.join(resolvedDir, 'MANIFEST.md')}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(HERE, 'collect-pdfs.mjs')) {
  main().catch((err) => {
    console.error(`collect-pdfs failed: ${err.message}`)
    process.exit(1)
  })
}
